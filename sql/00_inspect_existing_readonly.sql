-- MySQL 8.0：安全只读预检。连接队友的 library_db 后首先运行本文件。
-- 没有 CREATE/ALTER/DROP/INSERT/UPDATE/DELETE，绝不会覆盖现有数据。
SELECT DATABASE() AS connected_database, CURRENT_USER() AS connected_user, VERSION() AS mysql_version;
SELECT TABLE_NAME, TABLE_ROWS, ENGINE FROM information_schema.TABLES
  WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME;
SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT
  FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
  ORDER BY TABLE_NAME, ORDINAL_POSITION;
SELECT TABLE_NAME, INDEX_NAME, COLUMN_NAME, NON_UNIQUE
  FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
  ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;
