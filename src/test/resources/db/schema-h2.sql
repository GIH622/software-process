-- 仅用于H2测试数据库；保持真实library_db的列名。
CREATE TABLE IF NOT EXISTS reader_account(
 reader_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,card_no VARCHAR(30) NOT NULL UNIQUE,
 name VARCHAR(50) NOT NULL,password_md5 VARCHAR(64) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'NORMAL',borrowed_count INT NOT NULL DEFAULT 0,
 borrow_limit INT NOT NULL DEFAULT 5,phone VARCHAR(20),register_date DATE NOT NULL);
CREATE TABLE IF NOT EXISTS book_inventory(
 book_inventory_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,barcode VARCHAR(50) NOT NULL UNIQUE,
 isbn VARCHAR(20) NOT NULL,title VARCHAR(200) NOT NULL,author VARCHAR(100),
 category VARCHAR(50),location VARCHAR(50),status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
 created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS borrow_record(
 borrow_record_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,reader_id INT NOT NULL,
 book_inventory_id INT NOT NULL,borrow_time TIMESTAMP NOT NULL,
 expected_return_date DATE NOT NULL,actual_return_time TIMESTAMP,
 overdue_days INT NOT NULL DEFAULT 0,status VARCHAR(20) NOT NULL DEFAULT 'BORROWED',
 renew_count INT NOT NULL DEFAULT 0,
 FOREIGN KEY(reader_id) REFERENCES reader_account(reader_id),
 FOREIGN KEY(book_inventory_id) REFERENCES book_inventory(book_inventory_id));
CREATE TABLE IF NOT EXISTS operation_log(
 log_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,operation VARCHAR(30),
 operator VARCHAR(50),reader_id INT,book_isbn VARCHAR(20),
 detail VARCHAR(500),op_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
